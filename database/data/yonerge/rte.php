/**
 * Bir kadronun EK-2 satırlarını şart düğümlerine çevirir.
 *
 * @param  array<string, mixed>  $s
 * @param  array<string, string|int>|null  $donem
 * @return list<array<string, mixed>>
 */
$satirlar = function (array $s, ?array $donem, string $donemAd): array {
    $cocuklar = [];

    /** @var array<int, mixed> $m */
    $m = $s['makale'];
    $etiket = (string) $m[0];
    $grup = (string) $m[1];
    $puan = (int) $m[2];
    $sayi = (int) $m[3];

    $cocuklar[] = Kalip::puanDan(
        "{$donemAd}{$etiket} yayımlanmış makalelerden en az {$puan} puan almış olmak",
        [$grup], $puan, $donem, madde: 'EK-2/1',
    );
    $cocuklar[] = Kalip::adet(
        "{$donemAd}{$etiket} yayımlanmış makalelerin en az {$sayi} tanesinde başlıca yazar olmak",
        [$grup], $sayi, 'baslica', $donem, madde: 'EK-2/1',
    );

    if (isset($s['alt'])) {
        /** @var array<int, mixed> $a */
        $a = $s['alt'];
        $cocuklar[] = Kalip::puanDan(
            'Bu makale puanının en az '.((int) $a[2]).' puanının '.((string) $a[0])
            .' yayımlanmış makalelerden gelmesi',
            [(string) $a[1]], (int) $a[2], $donem, madde: 'EK-2/1-istisna',
        );
    }

    if (isset($s['adet'])) {
        /** @var array<int, mixed> $d */
        $d = $s['adet'];
        $cocuklar[] = Kalip::adet(
            "{$donemAd}".((string) $d[0]).' başlıca yazar olarak en az '.((int) $d[2])
            .' makale yayımlamış olmak',
            [(string) $d[1]], (int) $d[2], 'baslica', $donem, madde: 'EK-2/1-istisna',
        );
    }

    /** @var array<int, mixed> $b */
    $b = $s['bildiri'];
    $cocuklar[] = Kalip::puanDan(
        "{$donemAd}".((string) $b[0]).' en az '.((int) $b[2]).' puan almış olmak',
        [(string) $b[1]], (int) $b[2], $donem, madde: 'EK-2/2',
    );

    if (isset($s['kitap'])) {
        /** @var array<int, mixed> $k */
        $k = $s['kitap'];
        $cocuklar[] = Kalip::puanDan(
            "{$donemAd}".((string) $k[0]).' en az '.((int) $k[2]).' puan almış olmak',
